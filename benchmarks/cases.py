"""Benchmark case catalogue for the quantum circuit synthesizer.

Every case is a (target unitary, gate set, search settings) triple with an
`expect` verdict, so the runner can report both speed and correctness
(`match_expect`).  Expectations are derived from group-theoretic facts:

* "found": a circuit of length <= depth provably exists (the target is
    literally composed from gates in the searched set, or from a known
    decomposition).
* "not_found": provably unreachable because the target lies outside the
    group generated by the searched gate set (e.g. H is not generated by
    the diagonal gates {S, T}).
* None: uncertain / best-effort (e.g. hard targets where a solution may
    or may not sit within the searched depth).

Targets are constructed as explicit matrices (diagonals, Kronecker
products, seeded Haar-random unitaries), so the whole catalogue is
reproducible and independent of search outcomes.

Case families
-------------
basic              single named gates searched with (mostly) their own
                   gate set; fastest searches, used as smoke tests.
known-1q-pairs     two-gate products, searched under three different
                   gate-set subsets of Clifford+T.
not-found-1q       provably unreachable 1-qubit targets (honest negatives).
clifford24         every one of the 24 single-qubit Clifford matrices as
                   target, searched from just {H, S}.
known-2q-products  one 1-qubit Clifford composed with one 2-qubit gate
                   (CNOT/CNOT-reversed/CZ/SWAP), in both orders.
named-2q           curated named 2-qubit targets (CH, iSWAP, sqrtSWAP...).
haar-1q/haar-2q    Haar-random (seeded, reproducible) targets that cannot
                   be reached exactly; measures best-effort search quality.
scaling-beam       same target swept across beam widths (cost vs beam).
scaling-gateset    same target swept across growing gate-set subsets
                   (cost vs branching factor).
scaling-depth      same unreachable target swept across max depth
                   (cumulative expansions vs depth; exponential growth).
stress-3q          three-qubit targets at the edge of the practical range.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from fractions import Fraction
from functools import reduce

import numpy as np

from qcsynth.targets import TARGETS, get_target

CT_FILE = "gates/clifford_t.json"
RXY_FILE = "gates/universal_rxy.json"

HAAR_SEED = 20261106  # fixed so every run benchmarks identical targets


@dataclass
class Case:
    """One benchmark: a fully specified synthesis problem."""

    category: str
    label: str
    target: np.ndarray
    gates_file: str = CT_FILE
    gate_names: tuple = None          # subset of the gate-set file; None = all
    depth: int = 5
    beam: int = 400
    time_limit: float = 10.0
    expect: str = "found"             # "found" | "not_found" | None (either ok)
    quick_ok: bool = True             # included in --quick runs
    index: int = field(default=-1)    # filled in by build_cases()


# ------------------------------------------------------------------ helpers

_I2 = np.eye(2, dtype=np.complex128)


def _compose(seq):
    """Matrix of gates applied in order (first element applied first).

    Same convention as the search engine: V = G_k @ ... @ G_1.
    """
    dim = seq[0].shape[0]
    return reduce(lambda v, g: g @ v, seq, np.eye(dim, dtype=np.complex128))


def _haar_random(rng, dim):
    """Haar-random unitary via QR with phase-corrected R diagonal."""
    z = (rng.normal(size=(dim, dim)) + 1j * rng.normal(size=(dim, dim))) / np.sqrt(2)
    q, r = np.linalg.qr(z)
    phases = np.diagonal(r) / np.abs(np.diagonal(r))
    return (q * phases).astype(np.complex128)


def _single_qubit_cliffords():
    """Exactly the 24 projective single-qubit Clifford matrices.

    The group generated by H and S (global phases included) has exactly 192
    elements in the field Q(i, sqrt2); computing it exactly (no floats)
    and dividing out the 8 global phases yields the 24 projective
    representatives.  Float-only BFS mis-splits elements, so this whole
    computation is done with exact arithmetic (Fractions).
    Returns float complex128 matrices (one per projective class).
    """
    double = getattr(_single_qubit_cliffords, "_cache", None)
    if double is not None:
        return [m.copy() for m in double]

    F = Fraction
    HALF = F(1, 2)
    s2 = np.sqrt(2)

    def z_mul(u, v):                    # (a + b s) * (c + d s)
        a, b = u
        c, d = v
        return (a * c + 2 * b * d, a * d + b * c)

    def f_mul(x, y):                    # complex multiply in Q(i, s)
        ar, br, ai, bi = x
        cr, dr, ci, di = y
        rr = z_mul((ar, br), (cr, dr))
        ri = z_mul((ar, br), (ci, di))
        ir = z_mul((ai, bi), (cr, dr))
        ii = z_mul((ai, bi), (ci, di))
        return (rr[0] - ii[0], rr[1] - ii[1], ri[0] + ir[0], ri[1] + ir[1])

    def f_add(x, y):
        return (x[0] + y[0], x[1] + y[1], x[2] + y[2], x[3] + y[3])

    def matmul(A, B):
        return tuple(tuple(
            reduce(f_add, (f_mul(A[i][k], B[k][j]) for k in range(2)),
                   (F(0), F(0), F(0), F(0)))
            for j in range(2)) for i in range(2))

    ONE = (F(1), F(0), F(0), F(0))              # 1
    ZERO = (F(0), F(0), F(0), F(0))
    IUM = (F(0), F(0), F(1), F(0))              # i
    SQ = (F(0), HALF, F(0), F(0))               # sqrt2 / 2
    SQM = (F(0), -HALF, F(0), F(0))             # -sqrt2 / 2
    E45 = (F(0), HALF, F(0), HALF)              # e^{i pi/4}
    I2 = ((ONE, ZERO), (ZERO, ONE))
    Hm = ((SQ, SQ), (SQ, SQM))
    Sm = ((ONE, ZERO), (ZERO, IUM))

    # --- exact closure: 192 elements (24 projective x 8 global phases)
    elements = {I2}
    frontier = [I2]
    while frontier:
        nxt = []
        for m in frontier:
            for gen in (Hm, Sm):
                p = matmul(gen, m)
                if p not in elements:
                    elements.add(p)
                    nxt.append(p)
        frontier = nxt

    # --- one canonical representative per phase class (e^{i k pi/4} orbit)
    phases = [ONE]
    for _ in range(7):
        phases.append(f_mul(phases[-1], E45))

    def diag_mul(m, ph):
        return tuple(tuple(f_mul(m[i][j], ph) for j in range(2))
                     for i in range(2))

    classes = {}
    for m in elements:
        best = None
        for ph in phases:
            c = diag_mul(m, ph)
            key = c
            if best is None or key < best:
                best = key
        classes[best] = best

    assert len(classes) == 24, f"expected 24 Cliffords, got {len(classes)}"

    def to_float(m):
        out = np.zeros((2, 2), dtype=np.complex128)
        for i in range(2):
            for j in range(2):
                a, b, c, d = m[i][j]
                out[i, j] = (float(a) + float(b) * s2
                             + 1j * (float(c) + float(d) * s2))
        return out

    result = sorted((to_float(m) for m in classes.values()),
                    key=lambda arr: arr.round(9).tobytes())
    _single_qubit_cliffords._cache = result      # noqa: SLF001 - intentional
    return [m.copy() for m in result]


def _single(n_qubits, qubit, mat):
    """Embed a 1-qubit matrix on `qubit` of an n-qubit system (little-endian)."""
    factors = []
    for q in range(n_qubits - 1, -1, -1):   # most significant first
        factors.append(mat if q == qubit else _I2)
    return reduce(np.kron, factors)


def _is_identity(mat, tol=1e-9):
    return np.allclose(mat, np.eye(mat.shape[0]), atol=tol)


def _cnot_reversed():
    """CNOT with control/target swapped (well-defined: SWAP @ CNOT @ SWAP)."""
    swap, cnot = TARGETS["swap"], TARGETS["cnot"]
    return swap @ cnot @ swap


def _controlled_1q(control, mat):
    """Controlled-`mat` on a 2-qubit register with `control` as control qubit.

    Little-endian kron ordering (MSB first = higher qubit index); verified
    against the built-in CNOT for mat == X, control == 0.
    """
    p_on = np.diag([0, 1]).astype(complex)
    p_off = np.diag([1, 0]).astype(complex)
    if control == 0:     # control = LSB slot, target = MSB slot
        return np.kron(_I2, p_off) + np.kron(mat, p_on)
    else:                # control = MSB slot, target = LSB slot
        return np.kron(p_off, _I2) + np.kron(p_on, mat)


# ------------------------------------------------------------- catalogues

_1Q_GATES = {"X": TARGETS["x"], "Y": TARGETS["y"], "Z": TARGETS["z"],
             "H": TARGETS["h"], "S": TARGETS["s"], "T": TARGETS["t"]}


def _basic_cases():
    out = []
    for name in ("X", "Y", "Z", "H", "S", "T"):
        out.append(Case("basic", name, _1Q_GATES[name],
                        gate_names=(name,), depth=2, beam=50, expect="found"))
    out.append(Case("basic", "CNOT", TARGETS["cnot"],
                    gate_names=("CNOT",), depth=2, beam=50, expect="found"))
    # 3 CNOTs is the canonical SWAP decomposition: exercises 2q placements.
    out.append(Case("basic", "SWAP-as-3-CNOT", TARGETS["swap"],
                    gate_names=("CNOT",), depth=4, beam=50, expect="found"))
    return out


def _known_1q_pairs():
    """Two-gate products under subsets they belong to; provably found."""
    out = []
    subsets = [
        ("HT", ("H", "T"), 5, 300),
        ("HST", ("H", "S", "T"), 5, 300),
        ("XYZHST", ("X", "Y", "Z", "H", "S", "T"), 5, 400),
    ]
    for subset_label, subset, depth, beam in subsets:
        names = list(subset)
        for a in names:                       # a applies first
            for b in names:                   # b applies second
                target = _compose([_1Q_GATES[a], _1Q_GATES[b]])
                if _is_identity(target):
                    continue  # identity: beam_search starts there; degenerate
                out.append(Case(
                    "known-1q-pairs", f"{a},{b}|{subset_label}", target,
                    gate_names=subset, depth=depth, beam=beam, expect="found"))
    return out


def _not_found_1q_cases():
    """Targets provably outside the generated group (honest negatives)."""
    out = [
        # {S, T} products of diagonals: everything reached is diagonal up to
        # phase; cannot produce H or X (which mix the diagonal).
        Case("not-found-1q", "H|S,T", TARGETS["h"], gate_names=("S", "T"),
             depth=8, beam=600, time_limit=10.0, expect="not_found"),
        Case("not-found-1q", "X|S,T", TARGETS["x"], gate_names=("S", "T"),
             depth=8, beam=600, time_limit=10.0, expect="not_found"),
        # {X, Z} generates the (single-qubit) Pauli group only; no S phase.
        Case("not-found-1q", "S|X,Z", TARGETS["s"], gate_names=("X", "Z"),
             depth=8, beam=600, time_limit=10.0, expect="not_found"),
        # {H, S} generates exactly the 24 single-qubit Cliffords; no T phase.
        Case("not-found-1q", "T|H,S", TARGETS["t"], gate_names=("H", "S"),
             depth=8, beam=600, time_limit=10.0, expect="not_found"),
        Case("not-found-1q", "T|X,Y,Z,H,S", TARGETS["t"],
             gate_names=("X", "Y", "Z", "H", "S"),
             depth=8, beam=800, time_limit=10.0, expect="not_found"),
        # S dagger is S^3 but S itself is absent: diag(1, -i) needs -i phase.
        Case("not-found-1q", "Sdag|X,Z", TARGETS["t"].conj().T,
             gate_names=("X", "Z"), depth=8, beam=600, time_limit=10.0,
             expect="not_found"),
    ]
    return out


def _clifford24_cases():
    out = []
    for i, mat in enumerate(_single_qubit_cliffords()):
        out.append(Case("clifford24", f"C{i:02d}", mat,
                        gate_names=("H", "S"), depth=6, beam=150,
                        expect="found"))
    return out


def _known_2q_products():
    """One 1-qubit Clifford x one named 2-qubit gate, in both orders."""
    two_q = {
        "CNOT01": TARGETS["cnot"],
        "CNOT10": _cnot_reversed(),
        "CZ": TARGETS["cz"],
        "SWAP": TARGETS["swap"],
    }
    out = []
    for two_label, two_mat in two_q.items():
        for one_name, one_mat in _1Q_GATES.items():
            if one_name == "T":  # keep T outside: circuits stay short
                continue
            for pos in (0, 1):
                one = _single(2, pos, one_mat)
                one_label = f"{one_name}[{pos}]"
                for order in ("after", "before"):
                    seq = ([one, two_mat] if order == "after"
                           else [two_mat, one])
                    out.append(Case(
                        "known-2q-products",
                        f"{two_label} o {one_label} ({order})", _compose(seq),
                        depth=4, beam=300, expect="found"))
    return out


def _named_2q_cases():
    # iSWAP: little-endian diag(1, i, i, 1) on |01> and |10>; build it as
    # SWAP . S[0] . S[1] . CZ - all four gates are in the Clifford preset,
    # so exact synthesis within depth 5 is guaranteed.
    s0 = _single(2, 0, TARGETS["s"])
    s1 = _single(2, 1, TARGETS["s"])
    iswap = _compose([TARGETS["swap"], s0, s1, TARGETS["cz"]])
    out = [
        # CNOT(1,0) searched with CNOT only: the 3-CNOT decomposition exists.
        Case("named-2q", "CNOT10|CNOT-only", _cnot_reversed(),
             gate_names=("CNOT",), depth=5, beam=400, expect="found"),
        Case("named-2q", "iSWAP|full-preset", iswap,
             depth=5, beam=500, expect="found"),
        # Same matrix, sparser subset - fewer placements, harder search.
        Case("named-2q", "iSWAP|CNOT,H,S-only", iswap,
             gate_names=("CNOT", "H", "S"), depth=6, beam=600,
             expect="found"),
        # sqrt(SWAP) is non-Clifford; best-effort case (expect uncertain).
        Case("named-2q", "sqrt-SWAP", np.array(
            [[1, 0, 0, 0],
             [0, (.5 + .5j), (.5 - .5j), 0],
             [0, (.5 - .5j), (.5 + .5j), 0],
             [0, 0, 0, 1]], dtype=complex),
             depth=5, beam=800, time_limit=15.0, expect=None),
        # Controlled-H with control qubit 0 (constructed via projectors).
        Case("named-2q", "CH", _controlled_1q(0, TARGETS["h"]),
             depth=4, beam=600, expect="found"),
    ]
    return out


def _haar_cases():
    rng = np.random.default_rng(HAAR_SEED)
    out = []
    subsets = [("HST", ("H", "S", "T")), ("HT", ("H", "T")),
               ("RXY", None), ("RXY", None)]
    for i in range(10):
        sub_label, sub = subsets[i % len(subsets)]
        gates_file = RXY_FILE if sub_label == "RXY" else CT_FILE
        out.append(Case("haar-1q", f"haar1q-{i:02d}|{sub_label}",
                        _haar_random(rng, 2), gates_file=gates_file,
                        gate_names=sub, depth=8, beam=800, time_limit=8.0,
                        expect="not_found"))
    for i in range(5):
        target = _haar_random(rng, 4)
        gates_file = RXY_FILE if i == 4 else CT_FILE
        label = f"haar2q-{i:02d}" + ("-RXY" if i == 4 else "")
        out.append(Case("haar-2q", label, target, gates_file=gates_file,
                        depth=5, beam=1000, time_limit=12.0,
                        expect="not_found", quick_ok=False))
    return out


def _scaling_beam_cases():
    out = []
    swap = TARGETS["swap"]
    for beam in (25, 75, 225, 675, 2025):
        out.append(Case("scaling-beam", f"SWAP|beam-{beam}", swap,
                        depth=4, beam=beam, time_limit=30.0, expect="found",
                        quick_ok=beam <= 675))
    target = _haar_random(np.random.default_rng(HAAR_SEED), 4)
    for beam in (50, 200, 800):
        out.append(Case("scaling-beam", f"haar2q|beam-{beam}", target,
                        depth=5, beam=beam, time_limit=15.0,
                        expect="not_found", quick_ok=False))
    return out


def _scaling_gateset_cases():
    swap = TARGETS["swap"]
    subsets = [
        ("CNOT", ("CNOT",)),
        ("CNOT+H", ("CNOT", "H")),
        ("CNOT+CZ", ("CNOT", "CZ")),
        ("CNOT,CZ+H", ("CNOT", "CZ", "H")),
        ("CNOT,CZ,H+T", ("CNOT", "CZ", "H", "T")),
        ("full-CT", None),
    ]
    return [Case("scaling-gateset", f"SWAP|gates-{label}", swap,
                 gate_names=names, depth=5, beam=800, time_limit=20.0,
                 expect="found")
            for label, names in subsets]


def _scaling_depth_cases():
    target = _haar_random(np.random.default_rng(HAAR_SEED), 4)
    return [Case("scaling-depth", f"haar2q|depth-{d}", target,
                 depth=d, beam=300, time_limit=10.0, expect="not_found",
                 quick_ok=False)
            for d in range(2, 9)]


def _stress_3q_cases():
    h = get_target("h")
    # CCZ as an explicit diagonal; CCNOT = H(2) . CCZ . H(2) - standard and
    # unambiguous (little-endian: qubit 2 is the most significant bit).
    ccz = np.diag([1, 1, 1, 1, 1, 1, 1, -1]).astype(complex)
    h2 = _single(3, 2, h)
    ccnot = _compose([h2, ccz, h2])
    swap01 = reduce(np.kron, [_I2, TARGETS["swap"]])   # idle qubit 2
    cnot01 = reduce(np.kron, [_I2, TARGETS["cnot"]])
    return [
        Case("stress-3q", "H-H-H", reduce(np.kron, [TARGETS["h"]] * 3),
             depth=4, beam=600, expect="found"),
        Case("stress-3q", "CNOT|idle-q2", cnot01,
             depth=2, beam=600, expect="found"),
        Case("stress-3q", "SWAP|idle-q2", swap01,
             depth=4, beam=600, expect="found"),
        Case("stress-3q", "CCZ", ccz, depth=8, beam=800, time_limit=30.0,
             expect=None, quick_ok=False),
        Case("stress-3q", "CCNOT", ccnot, depth=9, beam=800, time_limit=30.0,
             expect=None, quick_ok=False),
    ]


def build_cases():
    """All benchmark cases, in stable order, with .index assigned."""
    cases = []
    cases += _basic_cases()
    cases += _known_1q_pairs()
    cases += _not_found_1q_cases()
    cases += _clifford24_cases()
    cases += _known_2q_products()
    cases += _named_2q_cases()
    cases += _haar_cases()
    cases += _scaling_beam_cases()
    cases += _scaling_gateset_cases()
    cases += _scaling_depth_cases()
    cases += _stress_3q_cases()
    for i, case in enumerate(cases):
        case.index = i
    return cases


if __name__ == "__main__":  # pragma: no cover
    groups = {}
    for case in build_cases():
        groups.setdefault(case.category, []).append(case)
    print(len(build_cases()), "\n")
    for cat, members in groups.items():
        print(f"{cat:<20} {len(members):4d}")
